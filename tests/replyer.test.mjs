test('Replyer failure, incomplete response and timeout fall back without changing original content', async () => {
  const failed = fixture(() => {
    throw Error('provider down')
  })
  assert.deepEqual(await failed.run(complete('原始结果')), complete('原始结果'))
  const truncated = fixture()
  truncated.llm.stream = () => stream(complete('半截 Replyer', 'max-tokens'))
  assert.equal(text(await truncated.run(complete('完整原始结果'))), '完整原始结果')
  const timeout = fixture(
    (_p, options) =>
      new Promise((_resolve, reject) =>
        options.signal.addEventListener('abort', () => reject(options.signal.reason), {
          once: true,
        }),
      ),
  )
  timeout.config.replyer.timeoutMs = 10
  const keepAlive = setTimeout(() => {}, 100)
  try {
    assert.equal(text(await timeout.run(complete('原始结果'))), '原始结果')
  } finally {
    clearTimeout(keepAlive)
  }
  assert.equal(timeout.status.replyer.lastReason, 'replyer-timeout')
})

test('user cancellation or plugin disposal aborts Replyer and never emits stale original text', async () => {
  for (const target of ['controller', 'lifetime']) {
    const f = fixture(
      (_p, options) =>
        new Promise((_resolve, reject) => {
          options.signal.addEventListener('abort', () => reject(options.signal.reason), {
            once: true,
          })
          f[target].abort()
        }),
    )
    await assert.rejects(f.run(complete('不能在取消后输出的草稿')))
    assert.equal(f.status.replyer.rendered, 0)
    assert.equal(f.status.replyer.fallback, 0)
  }
})

