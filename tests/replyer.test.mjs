test('main stream exceptions propagate, preserving already generated chunks for native settlement', async () => {
  const f = fixture(),
    seen = []
  const input = async function* () {
    yield { type: 'text-delta', index: 0, text: '部分' }
    throw Error('broken stream')
  }
  await assert.rejects(
    (async () => {
      for await (const c of f.wrap(f.options, input)) seen.push(c)
    })(),
    /broken stream/,
  )
  assert.equal(text(seen), '部分')
  assert.equal(f.calls.length, 0)
})

