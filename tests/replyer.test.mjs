const payloadOf = (options) => ({
  replyReference:
    options.messages
      .map((m) => m.content[0].text)
      .find((s) => s.startsWith('【回复信息参考】\n'))
      ?.slice('【回复信息参考】\n'.length) ?? '',
  history: options.messages.filter((m) => ['user', 'model'].includes(m.source.kind)),
  turnReference:
    options.messages.map((m) => m.content[0].text).find((s) => s.startsWith('【有来源的记忆】')) ??
    '',
})

const stream = async function* (chunks) {
  yield* chunks
}
const collect = async (iterable) => {
  const out = []
  for await (const c of iterable) out.push(c)
  return out
}
const text = (chunks) =>
  chunks
    .filter((c) => c.type === 'text-delta')
    .map((c) => c.text)
    .join('')
const usage = { inputTokens: 10, outputTokens: 5, cacheReadTokens: 2, totalTokens: 17 }
const complete = (value, reason = 'stop') => [
  { type: 'block-start', index: 3, blockType: 'text' },
  { type: 'text-delta', index: 3, text: value },
  { type: 'block-end', index: 3, block: { type: 'text', text: value } },
  { type: 'usage', usage },
  { type: 'finish', reason: { kind: reason }, replayState: { response: 'original-private-state' } },
]
function fixture(render = (p) => '嗯，' + p.replyReference) {
  const controller = new AbortController(),
    lifetime = new AbortController(),
    calls = [],
    status = { calls: 0 }
  const config = normalize()
  const state = {
    messages: [{ id: 'u', text: '现在说说你的想法' }],
    plan: '本轮记忆：用户喜欢爵士乐',
    replyContext: { memories: [{ text: '用户喜欢爵士乐' }] },
    agent: {
      session: {
        deriveMessages: () => [
          {
            role: 'user',
            source: { kind: 'plugin' },
            content: [{ type: 'text', text: 'NOT_HUMAN' }],
          },
          {
            role: 'user',
            source: { kind: 'user' },
            content: [{ type: 'text', text: '最近在听爵士乐' }],
          },
          {
            role: 'assistant',
            source: { kind: 'model' },
            content: [
              { type: 'tool-call', name: 'pwsh' },
              { type: 'text', text: 'INTERNAL_TOOL_PLAN' },
            ],
          },
          {
            role: 'assistant',
            source: { kind: 'model' },
            content: [{ type: 'text', text: '上次的真实发言' }],
          },
        ],
      },
    },
  }
  const llm = {
    stream(options) {
      calls.push(options)
      return (async function* () {
        const payload = payloadOf(options)
        const value = await render(payload, options)
        yield* complete(value)
      })()
    },
  }
  const wrap = createReplyer({
    llm,
    config: () => config,
    stateFor: (signal) => (signal === controller.signal ? state : undefined),
    status,
    lifetimeSignal: lifetime.signal,
  })
  const options = {
    provider: 'provider',
    model: 'main-model',
    signal: controller.signal,
    system: 'HOST_TOOL_POLICY',
    tools: [{ name: 'dangerous-tool' }],
    reasoningEffort: 'high',
  }
  return {
    controller,
    lifetime,
    calls,
    status,
    config,
    state,
    llm,
    wrap,
    options,
    run: (chunks) => collect(wrap(options, () => stream(chunks))),
  }
}

test('final text is generated by a separate tool-free Replyer with persona, memory and clean history', async () => {
  const f = fixture()
  const result = await f.run(complete('查到的结果是 42。'))
  assert.equal(text(result), '嗯，查到的结果是 42。')
  assert.equal(f.calls.length, 1)
  const request = f.calls[0],
    payload = payloadOf(request)
  assert.equal(request.provider, 'provider')
  assert.equal(request.model, 'main-model')
  assert.equal(request.tools, undefined)
  assert.equal(request.reasoningEffort, undefined)
  assert.notEqual(request.signal, f.options.signal)
  assert.match(request.system, /简短.*口语/)
  assert.ok(!request.system.includes('HOST_TOOL_POLICY'))
  assert.match(payload.turnReference, /爵士乐/)
  assert.ok(!JSON.stringify(payload.history).includes('NOT_HUMAN'))
  assert.ok(!JSON.stringify(payload.history).includes('INTERNAL_TOOL_PLAN'))
  assert.match(JSON.stringify(payload.history), /真实发言/)
  assert.equal(f.status.replyer.rendered, 1)
})

