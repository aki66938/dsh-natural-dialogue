test('Replyer preserves actual dialogue roles, does not duplicate the current user, and separates reference', () => {
  const request = buildReplyerRequest({
    persona: normalize().persona,
    history: [
      { id: 'u1', role: 'user', text: '有点累' },
      { id: 'a1', role: 'assistant', source: { provider: 'p', model: 'm' }, text: '那先歇会。' },
      { id: 'u2', role: 'user', text: '你陪我聊聊' },
    ],
    current: [{ id: 'u2', text: '你陪我聊聊' }],
    reference: '',
    conversational: true,
    chatChars: 240,
  })
  assert.deepEqual(
    request.messages.slice(0, 3).map((m) => m.role),
    ['user', 'assistant', 'user'],
  )
  assert.equal(request.messages.filter((m) => m.id === 'u2').length, 1)
  assert.ok(!request.messages.some((m) => m.content[0].text.startsWith('【回复信息参考】')))
  assert.ok(!request.system.includes('先说自己的判断'))
  assert.ok(!request.system.includes('说明分工'))
})

