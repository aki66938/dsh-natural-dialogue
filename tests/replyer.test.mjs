test('disabling Replyer while generation is in flight falls back to the native response', async () => {
  let release, started
  const gate = new Promise((r) => (release = r)),
    begin = new Promise((r) => (started = r))
  const f = fixture(async () => {
    started()
    await gate
    return '不应显示的角色改写'
  })
  const original = complete('原始回复'),
    pending = f.run(original)
  await begin
  f.config.replyer.enabled = false
  release()
  assert.deepEqual(
    (await pending).filter((c) => c.type !== 'usage'),
    original.filter((c) => c.type !== 'usage'),
  )
  assert.equal(f.status.replyer.lastReason, 'replyer-disabled-during-turn')
})
